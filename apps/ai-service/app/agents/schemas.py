"""Pydantic validation schemas for intent classification, planning, and workflow APIs."""

from enum import Enum
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field


class WorkflowIntent(str, Enum):
    KNOWLEDGE_QUESTION = "knowledge_question"
    TICKET_LOOKUP = "ticket_lookup"
    TICKET_CREATION_REQUEST = "ticket_creation_request"
    TICKET_UPDATE_REQUEST = "ticket_update_request"
    USER_LOOKUP = "user_lookup"
    SUPPORT_HISTORY_QUERY = "support_history_query"
    GENERAL_QUESTION = "general_question"
    NEEDS_CLARIFICATION = "needs_clarification"
    UNSUPPORTED_REQUEST = "unsupported_request"


class WorkflowIntentClassification(BaseModel):
    """Structured LLM classification output for incoming user inquiry."""

    intent: WorkflowIntent = Field(..., description="Categorized primary intent")
    summary: str = Field(..., min_length=1, max_length=500, description="Brief summary of request")
    urgency: str = Field(default="medium", description="Urgency: low, medium, high, urgent")
    confidence_label: str = Field(default="high", description="Qualitative confidence: high, medium, low")
    required_information: List[str] = Field(default_factory=list, description="Missing parameters if clarification is needed")
    expected_action_type: str = Field(default="read", description="Expected operational mode: read, propose_mutation, clarify, none")
    reasoning_summary: str = Field(default="", description="Internal diagnostic reasoning summary")


class WorkflowExecutionPlan(BaseModel):
    """Bounded, validated execution plan specifying at most one primary tool action (Module 12 legacy compatibility)."""

    intent: WorkflowIntent
    objective: str = Field(..., description="Clear operational objective for the run")
    selected_tool: Optional[str] = Field(None, description="Allowlisted tool identifier or None")
    tool_arguments: Dict[str, Any] = Field(default_factory=dict, description="Validated input arguments for selected tool")
    action_type: str = Field(default="read", description="Action classification: read, propose_mutation, or none")
    requires_approval: bool = Field(default=False, description="Whether human approval is required (strictly proposal-only)")


# Module 13 Multi-Step Structured Planning & Progress Schemas


class PlanStep(BaseModel):
    """Discrete, ordered execution step within an agent's multi-step plan."""

    step_id: str = Field(..., description="Unique step identifier, e.g. 'step_1'")
    tool_name: str = Field(..., description="Approved registered tool name")
    action_type: str = Field(default="read", description="Action type: read, mutation_proposal, none")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Validated arguments for the tool")
    depends_on: List[str] = Field(default_factory=list, description="List of prior step_ids required for this step")
    condition: Optional[str] = Field(None, description="Optional conditional execution rule")
    expected_output: Optional[str] = Field(None, description="Description of expected step output")


class MultiStepExecutionPlan(BaseModel):
    """Structured, ordered multi-step execution plan generated by LLM."""

    objective: str = Field(..., description="Overarching operational objective")
    steps: List[PlanStep] = Field(default_factory=list, min_length=0, max_length=5, description="Ordered sequence of execution steps")
    reasoning: Optional[str] = Field(None, description="Diagnostic planning rationale")


class StepProgressDecision(str, Enum):
    """Outcome decision evaluated after each tool execution step."""

    NEXT_STEP = "next_step"
    REPLAN = "replan"
    FINALIZE = "finalize"


class ProgressEvaluation(BaseModel):
    """Structured progress assessment determining next graph edge."""

    decision: StepProgressDecision = Field(..., description="Next routing decision")
    rationale: str = Field(..., description="Explanation for progress decision")
    replan_reason: Optional[str] = Field(None, description="Reason if replanning was triggered")
    revised_objective: Optional[str] = Field(None, description="Updated objective if scope refined")


class RunWorkflowRequest(BaseModel):
    """Internal service request to launch an OpsPilot LangGraph workflow run."""

    request_id: str = Field(..., description="Unique request UUID for idempotency")
    organization_id: str = Field(..., description="Target tenant organization UUID")
    query: str = Field(..., min_length=1, max_length=5000, description="User question or operational prompt")
    workflow_version: str = Field(default="v1.0", description="Workflow graph version")
    thread_id: Optional[str] = Field(None, description="Optional conversation/thread UUID for state tracking")
    # Trusted runtime context fields passed from Node.js Express authority
    authenticated_user_id: str
    delegated_authorization_token: str
    permitted_scopes: List[str] = Field(default_factory=list)
    organization_role: str = "member"
    correlation_id: Optional[str] = None


class WorkflowRunData(BaseModel):
    """Standardized result returned by workflow execution and status endpoints."""

    run_id: str
    thread_id: str
    organization_id: str
    status: str  # completed, awaiting_approval, failed, blocked, running
    intent: Optional[str] = None
    selected_tool: Optional[str] = None
    answer: Optional[str] = None
    citations: List[Dict[str, Any]] = Field(default_factory=list)
    insufficient_evidence: bool = False
    requires_approval: bool = False
    proposal: Optional[Dict[str, Any]] = None
    proposal_id: Optional[str] = None
    error_code: Optional[str] = None
    duration_ms: Optional[float] = None
    # Module 13 Multi-Step Progression Telemetry
    total_steps: int = 0
    completed_steps: List[str] = Field(default_factory=list)
    tool_call_count: int = 0
    replan_count: int = 0
    action_proposals: List[Dict[str, Any]] = Field(default_factory=list)
    memory_proposals: List[Dict[str, Any]] = Field(default_factory=list)
    execution_summary: Optional[str] = None


class RunWorkflowResponse(BaseModel):
    success: bool
    data: Optional[WorkflowRunData] = None
    error: Optional[Dict[str, Any]] = None


class WorkflowStatusResponse(BaseModel):
    success: bool
    data: Optional[WorkflowRunData] = None
    error: Optional[Dict[str, Any]] = None


class ResumeWorkflowRequest(BaseModel):
    thread_id: str = Field(..., description="Thread ID of the interrupted workflow run")
    proposal_id: str = Field(..., description="Action proposal identifier")
    decision: str = Field(..., pattern=r"^(approved|rejected)$", description="'approved' or 'rejected'")
    decided_by: Optional[str] = Field(None, description="UUID of the user who approved/rejected")
    decision_reason: Optional[str] = Field(None, description="Notes or rejection rationale")
    execution_result: Optional[Dict[str, Any]] = Field(None, description="Execution outcome if approved")


class ResumeWorkflowResponse(BaseModel):
    success: bool
    data: Optional[WorkflowRunData] = None
    error: Optional[Dict[str, Any]] = None


class WorkflowAnalyticsSummary(BaseModel):
    total_runs: int = 0
    successful_runs: int = 0
    failed_runs: int = 0
    waiting_approval_runs: int = 0
    running_runs: int = 0
    success_rate: float = 0.0
    avg_duration_ms: float = 0.0
    total_tool_calls: int = 0
    recent_runs: List[Dict[str, Any]] = Field(default_factory=list)


class WorkflowAnalyticsResponse(BaseModel):
    success: bool
    data: Optional[WorkflowAnalyticsSummary] = None
    error: Optional[Dict[str, Any]] = None


class WorkflowRunListItem(BaseModel):
    id: str
    run_id: str
    thread_id: str
    organization_id: str
    user_id: str
    workflow_name: str
    workflow_version: str
    status: str
    intent: Optional[str] = None
    selected_tool: Optional[str] = None
    requires_approval: bool = False
    proposal_id: Optional[str] = None
    error_code: Optional[str] = None
    started_at: Optional[str] = None
    completed_at: Optional[str] = None
    duration_ms: Optional[float] = None
    total_steps: int = 0
    completed_steps_count: int = 0
    tool_call_count: int = 0
    created_at: Optional[str] = None


class WorkflowRunListResult(BaseModel):
    items: List[WorkflowRunListItem]
    total: int
    page: int
    limit: int
    total_pages: int


class WorkflowRunListResponse(BaseModel):
    success: bool
    data: Optional[WorkflowRunListResult] = None
    error: Optional[Dict[str, Any]] = None


