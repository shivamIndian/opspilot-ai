import React from 'react';
import { cn } from '@/utils/cn';

export interface CardProps extends React.HTMLAttributes<HTMLDivElement> {
  hoverable?: boolean;
}

export const Card = React.forwardRef<HTMLDivElement, CardProps>(
  ({ className, hoverable = false, children, ...props }, ref) => {
    return (
      <div
        ref={ref}
        className={cn(
          'bg-white dark:bg-[#0F172A] border border-slate-200 dark:border-[#273449] rounded-xl shadow-sm transition-all duration-150',
          hoverable && 'hover:shadow-md hover:border-slate-300 dark:hover:border-[#3A4A63] hover:dark:bg-[#111C31]/90',
          className
        )}
        {...props}
      >
        {children}
      </div>
    );
  }
);
Card.displayName = 'Card';

